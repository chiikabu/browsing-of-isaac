/* host_lua.c -- the 59-symbol Lua binding.
 *
 * 14,011 call sites, 62.2% of all IAT traffic, and 95% of the remaining
 * unwired exposure. The ABI groundwork is settled (stock upstream 5.3.3,
 * default numeric config, cdecl throughout), so this is construction.
 *
 * THREE THINGS THAT WOULD SILENTLY CORRUPT EVERYTHING IF GOT WRONG
 *
 * 1. C FUNCTIONS FLOW BOTH WAYS. lua_pushcclosure (1,064 sites) hands Lua a
 *    GUEST function pointer -- a lifted-code VA. Lua would later call it as a
 *    host `int (*)(lua_State *)`, which is not what it is. Every guest
 *    lua_CFunction therefore goes through a TRAMPOLINE that builds a CpuState
 *    and re-enters guest code properly.
 *
 *    The obvious trampoline design -- one shared host function plus an extra
 *    upvalue holding the guest VA -- is WRONG here. Prepending an upvalue
 *    shifts every lua_upvalueindex(i) the guest computes (the macro is
 *    LUA_REGISTRYINDEX - i, expanded inside guest code, so it cannot be
 *    intercepted), and appending one cannot be located without knowing the
 *    upvalue count. So instead there is a POOL of distinct trampolines, each
 *    hard-coding its own slot. Upvalue indices are left exactly as the guest
 *    expects, and pool exhaustion is loud rather than silent.
 *
 * 2. LUA MUST ALLOCATE IN THE GUEST ARENA. Lua's objects are reachable from
 *    guest pointers (lua_State*, userdata, string bodies), so they have to be
 *    guest-addressable. Routing Lua's allocator to the host allocator would
 *    put every Lua object above the guard -- the same correctness bug already
 *    caught with guest malloc, but affecting 14,011 call sites instead of one.
 *
 * 3. THE RETURN CONVENTIONS DIFFER BY TYPE. lua_Number (double) returns in
 *    st(0); lua_Integer (long long) returns in EDX:EAX; and a 64-bit by-value
 *    argument occupies TWO stack slots, which is why lua_rawgeti(L,int,int64)
 *    has a 16-byte argument area. These are encoded once, below, rather than
 *    per symbol.
 *
 * Build: see scripts/recomp/host/lua_build.py. Compiles to a loud stub layer
 * when lua.h is absent, so the host module still links.
 */

