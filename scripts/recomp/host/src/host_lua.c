    /* luaL_newstate uses the default allocator; we must not. lua_newstate with
     * our guest-arena allocator is the equivalent that keeps Lua's objects
     * guest-addressable. */
    lua_State *L = lua_newstate(isaac_lua_alloc, NULL);
    ret_ptr(cpu, L);
