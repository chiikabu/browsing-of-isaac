/* ---- guest pointer plumbing -------------------------------------------- */

#define L_ARG(n)   ((lua_State *)isaac_g(isaac_arg(cpu, (n))))
#define I_ARG(n)   ((int)isaac_arg(cpu, (n)))
#define S_ARG(n)   (isaac_is_guest_va(isaac_arg(cpu, (n)))                     \
                        ? (const char *)isaac_g(isaac_arg(cpu, (n))) : NULL)
#define P_ARG(n)   ((void *)isaac_g(isaac_arg(cpu, (n))))

/* A 64-bit by-value argument occupies two stack slots. */
static lua_Integer i64_arg(const CpuState *cpu, unsigned slot) {
    uint64_t lo = isaac_arg(cpu, slot), hi = isaac_arg(cpu, slot + 1);
    return (lua_Integer)(lo | (hi << 32));
}
static lua_Number num_arg(const CpuState *cpu, unsigned slot) {
    uint64_t lo = isaac_arg(cpu, slot), hi = isaac_arg(cpu, slot + 1);
    uint64_t b = lo | (hi << 32);
    lua_Number d;
    memcpy(&d, &b, 8);
    return d;
}
/* lua_Number returns in st(0); the lifter models x87 as a double in the low
 * 8 bytes, so this is a plain 8-byte store. */
static void ret_num(CpuState *cpu, lua_Number v) { memcpy(cpu->ST0, &v, 8); }
/* lua_Integer returns in EDX:EAX. */
static void ret_int(CpuState *cpu, lua_Integer v) {
    cpu->EAX = (uint32_t)(uint64_t)v;
    cpu->EDX = (uint32_t)((uint64_t)v >> 32);
}
static void ret_ptr(CpuState *cpu, const void *p) {
    cpu->EAX = p ? isaac_va(p) : 0;
}

/* ---- 2. the allocator --------------------------------------------------- */

extern uint32_t isaac_guest_alloc(uint32_t n);
extern void     isaac_guest_free(uint32_t p);
extern uint32_t isaac_guest_realloc(uint32_t p, uint32_t n);

static void *isaac_lua_alloc(void *ud, void *ptr, size_t osize, size_t nsize) {
    (void)ud; (void)osize;
    if (nsize == 0) {
        if (ptr) isaac_guest_free(isaac_va(ptr));
        return NULL;
    }
    uint32_t p = isaac_guest_realloc(ptr ? isaac_va(ptr) : 0, (uint32_t)nsize);
    return p ? isaac_g(p) : NULL;
}

/* ---- 1. the trampoline pool --------------------------------------------- */

#define LUA_TRAMPOLINES 2048

static uint32_t g_tramp_va[LUA_TRAMPOLINES];   /* guest lua_CFunction VA */
static unsigned g_tramp_n;

static int call_guest_cfunction(lua_State *L, unsigned slot) {
    uint32_t fn = g_tramp_va[slot];
    CpuState cpu;
    memset(&cpu, 0, sizeof cpu);
    cpu.FS_OFFSET = ISAAC_TEB_VA;
    /* A fresh stack window per re-entry: Lua may call us from arbitrary depth
     * and the guest's own frame chain must not be clobbered. */
    cpu.ESP = ISAAC_STACK_TOP_VA - 0x8000 - slot * 0x400;
    cpu.ESP -= 4;
    isaac_w32(cpu.ESP, isaac_va(L));      /* the sole argument, cdecl */
    cpu.ESP -= 4;
    isaac_w32(cpu.ESP, 0);                /* return address */
    isaac_guest_call(fn, &cpu);
    return (int)cpu.EAX;                  /* number of results */
}

