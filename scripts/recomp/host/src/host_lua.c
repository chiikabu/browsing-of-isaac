LUA_SHIM(lua_newstate) {
    /* The game installs its own cdecl 4-arg lua_Alloc. Honouring it would call
     * back into guest code for every allocation; ours already allocates from
     * the guest arena, which is what that allocator exists to guarantee. */
    uint32_t guest_alloc = isaac_arg(cpu, 0);
    if (guest_alloc)
        isaac_log("[isaac][lua] lua_newstate: the guest's lua_Alloc 0x%08x is "
                  "replaced by the host guest-arena allocator, which already "
                  "satisfies the same requirement (allocations must be "
                  "guest-addressable).", guest_alloc);
    ret_ptr(cpu, lua_newstate(isaac_lua_alloc, NULL));
}
